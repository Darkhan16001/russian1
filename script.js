document.addEventListener("keydown", event => {
  if (event.key === "ArrowRight") {
    nextSlide();
  }

  if (event.key === "ArrowLeft") {
    previousSlide();
  }

  const slide = slides[current];

  if (
    slide.type === "quiz" &&
    answers[slide.questionIndex] === undefined
  ) {
    const keys = {
      "1": 0,
      "2": 1,
      "3": 2,
      "4": 3
    };

    if (keys[event.key] !== undefined) {
      chooseAnswer(
        slide.questionIndex,
        keys[event.key]
      );
    }
  }
});

