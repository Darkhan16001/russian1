// 19. ТАЙМЕР УРОКА
// =====================================

function getElapsed() {
  if (!timerRunning) {
    return savedSeconds;
  }

  return savedSeconds +
    Math.floor((Date.now() - timerStartedAt) / 1000);
}

function updateTimer() {
  const total = Math.max(0, getElapsed());

  const minutes = Math.floor(total / 60);
  const seconds = total % 60;

  const display =
    String(minutes).padStart(2, "0") +
    ":" +
    String(seconds).padStart(2, "0");

  const timer = document.getElementById("timer");

  timer.textContent = display;

  timer.style.color =
    total >= 4800 ? "#d73550" : "#078556";
}

function toggleTimer() {
  if (timerRunning) {
    savedSeconds = getElapsed();
    timerRunning = false;
  } else {
    timerStartedAt = Date.now();
    timerRunning = true;
  }

  document.getElementById("timerButton").textContent =
    timerRunning ? "⏸ Пауза" : "▶ Таймер";

  updateTimer();
}

function resetTimer() {
  savedSeconds = 0;
  timerStartedAt = 0;
  timerRunning = false;

  document.getElementById("timerButton").textContent =
    "▶ Таймер";

  updateTimer();
}

