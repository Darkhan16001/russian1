function renderQuiz(s) {
  const i = s.questionIndex;
  const q = questions[i];

  const selected = answers[i];
  const done = selected !== undefined;

  const options = q[1].map((option, j) => {
    let cls = "";

    if (done) {
      cls = j === q[2]
        ? "correct"
        : j === selected ? "wrong" : "";
    }

    return `
      <button
        class="quiz-option ${cls}"
        onclick="chooseAnswer(${i},${j})"
        ${done ? "disabled" : ""}
      >
        ${"ABCD"[j]}. ${option}
      </button>
    `;
  }).join("");

  const feedback = done
    ? `
      <div class="quiz-feedback">
        <h3 class="${selected === q[2] ? "green" : "red"}">
          ${selected === q[2] ? "✓ Правильно!" : "✕ Неверно"}
        </h3>
        <p>Верный ответ: <strong>${q[1][q[2]]}</strong></p>
      </div>
    `
    : "";

  screen.innerHTML = `
    <div class="eyebrow">
      ВОПРОС ${i + 1} ИЗ ${questions.length}
    </div>

    <h2>${q[0]}</h2>
    <p>Выберите один вариант.</p>

    <div class="quiz-options">
      ${options}
    </div>

    ${feedback}
  `;
}

function chooseAnswer(i, j) {
  if (answers[i] === undefined) {
    answers[i] = j;
    render();
  }
}

function renderResult() {
  const score = questions.reduce(
    (n, q, i) => n + (answers[i] === q[2] ? 1 : 0),
    0
  );

  document.getElementById("quizResult").innerHTML = `
    <div class="score">${score}/${questions.length}</div>
    <p style="text-align:center">
      Правильных ответов: ${score}
    </p>
  `;
}

function restartQuiz() {
  answers = {};
  current = quizStart;
  render();
}

