// 3. ИСПРАВЛЕННАЯ ЗАГРУЗКА ФОТО
// =======================================

function initializePhotos() {
  const images = screen.querySelectorAll("img[data-photo]");

  images.forEach(image => {
    const photoType = image.dataset.photo;
    const sources = PHOTOS[photoType];

    function loadNext() {
      const next = Number(image.dataset.index) + 1;

      if (next < sources.length) {
        image.dataset.index = String(next);
        image.src = sources[next];
      } else {
        image.style.display = "none";

        const fallback = image.parentElement.querySelector(
          ".photo-fallback"
        );

        if (fallback) {
          fallback.classList.remove("hidden");
        }
      }
    }

    image.addEventListener("error", loadNext);

    if (image.complete && image.naturalWidth === 0) {
      loadNext();
    }
  });
}

