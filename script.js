function updateClock() {
  document.getElementById("clock").textContent =
    new Date().toLocaleTimeString("ru-RU", {
      timeZone: "Asia/Almaty",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false
    });
}

function elapsedSeconds() {
  return running
    ? savedSeconds + Math.floor((Date.now() - startedAt) / 1000)
    : savedSeconds;
}

function updateTimer() {
  const n = elapsedSeconds();
  const m = Math.floor(n / 60);
  const s = n % 60;

  const el = document.getElementById("timer");

  el.textContent =
    `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;

  el.style.color = n >= 4800 ? "#cc3451" : "#087850";
}

function toggleTimer() {
  if (running) {
    savedSeconds = elapsedSeconds();
    running = false;
  } else {
    startedAt = Date.now();
    running = true;
  }

  document.getElementById("timerButton").textContent =
    running ? "⏸ Пауза" : "▶ Таймер";

  updateTimer();
}

function resetTimer() {
  savedSeconds = 0;
  startedAt = 0;
  running = false;

  document.getElementById("timerButton").textContent = "▶ Таймер";
  updateTimer();
}

document.addEventListener("keydown", e => {
  if (e.key === "ArrowRight") nextSlide();
  if (e.key === "ArrowLeft") previousSlide();

  const s = slides[current];

  if (
    s.type === "quiz" &&
    answers[s.questionIndex] === undefined &&
    "1234".includes(e.key)
  ) {
    chooseAnswer(s.questionIndex, Number(e.key) - 1);
  }
});

