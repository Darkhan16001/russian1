function picture(file, caption) {
  return `
    <figure class="photo">
      <img data-asset src="${ASSETS}${file}" alt="${caption}">
      <div class="asset-fail hidden">
        Фотография не загружена.
        Загрузите папку assets вместе с сайтом.
      </div>
      <figcaption>${caption}</figcaption>
    </figure>
  `;
}

function presentation(section, title, filename, description) {
  add(
    section,
    "ПРЕЗЕНТАЦИЯ",
    title,
    `
      <figure class="presentation">
        <img
          data-asset
          src="${ASSETS}slides/${filename}"
          alt="${title}"
        >
        <div class="asset-fail hidden">
          Слайд не найден.
          Проверьте папку assets/slides.
        </div>
        <figcaption>${description}</figcaption>
      </figure>
    `,
    "presentation"
  );
}

function setupImages() {
  screen.querySelectorAll("img[data-asset]").forEach(img => {
    const fail = () => {
      img.classList.add("hidden");
      img.nextElementSibling?.classList.remove("hidden");
    };

    img.addEventListener("error", fail);

    if (img.complete && img.naturalWidth === 0) {
      fail();
    }
  });
}

function reveal(text) {
  return `
    <button class="action" onclick="showAnswer()">
      Показать ответ
    </button>
    <div id="answerBox" class="answer hidden">${text}</div>
  `;
}

