function nextSlide() {
  if (currentSlide < slides.length - 1) {
    currentSlide++;
    renderSlide();
  }
}

function previousSlide() {
  if (currentSlide > 0) {
    currentSlide--;
    renderSlide();
  }
}

function goHome() {
  currentSlide = 0;
  renderSlide();
}

function showAnswer() {
  shownAnswers[currentSlide] = true;

  const box = document.getElementById("answerBox");

  if (box) {
    box.classList.remove("hidden");
  }
}

