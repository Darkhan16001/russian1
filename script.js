// 5. ДВЕ ПРЕЗЕНТАЦИИ ВНУТРИ САЙТА
// ======================================

function presentationSlides(
  section,
  title,
  prefix,
  count,
  pdfName,
  originalName,
  description
) {

  add(
    section,
    "ПРЕЗЕНТАЦИЯ · " + count + " СЛАЙДОВ",
    title,
    `
      <p>${description}</p>

      ${callout(
        "Все слайды презентации размещены прямо внутри сайта. Нажимайте «Далее» слева, чтобы их просматривать.",
        "blue"
      )}

      <div class="presentation-actions">
        <a class="action"
           href="assets/${pdfName}"
           target="_blank">
          Открыть презентацию PDF
        </a>

        <a class="action"
           href="assets/${originalName}"
           download>
          Скачать оригинал PowerPoint
        </a>
      </div>
    `
  );

  for (let i = 1; i <= count; i++) {
    const number = String(i).padStart(2, "0");

    const imagePath =
      "assets/slides/" + prefix + "-" + number + ".webp";

    const pdfPath =
      "assets/" + pdfName + "#page=" + i;

    add(
      section,
      "ПРЕЗЕНТАЦИЯ · " + i + " ИЗ " + count,
      title,
      `
        <figure class="presentation-slide">
          <img
            src="${imagePath}"
            alt="${title}. Слайд ${i}"
            loading="eager"
          >
          <figcaption>
            Слайд ${i} из ${count}
          </figcaption>
        </figure>

        <div class="presentation-actions">
          <a class="action"
             href="${pdfPath}"
             target="_blank">
            ⛶ Открыть крупнее
          </a>
        </div>
      `,
      "presentation"
    );
  }
}

