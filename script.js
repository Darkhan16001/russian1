function renderQuiz(slide) {
  const i = slide.questionIndex;
  const q = questions[i];

  const selected = answers[i];
  const answered = selected !== undefined;

  let optionsHTML = "";

  q[1].forEach((option, index) => {
    let className = "";

    if (answered) {
      if (index === q[2]) {
        className = "correct";
      } else if (index === selected) {
        className = "wrong";
      }
    }

    optionsHTML += `
      <button
        class="quiz-option ${className}"
        onclick="chooseAnswer(${i}, ${index})"
        ${answered ? "disabled" : ""}
      >
        ${"ABCD"[index]}. ${option}
      </button>
    `;
  });

  let feedbackHTML = "";

  if (answered) {
    const correct = selected === q[2];

    feedbackHTML = `
      <div class="quiz-feedback">
        <h3 class="${correct ? "green" : "red"}">
          ${correct ? "✓ Правильно!" : "✕ Неверно"}
        </h3>

        <p>
          <strong>Правильный ответ:</strong>
          ${q[1][q[2]]}
        </p>
      </div>
    `;
  }

  screen.innerHTML = `
    <div class="eyebrow">
      ВОПРОС ${i + 1} ИЗ ${questions.length}
    </div>

    <h2>${q[0]}</h2>

    <p>Выберите один правильный ответ.</p>

    <div class="quiz-options">
      ${optionsHTML}
    </div>

    ${feedbackHTML}
  `;
}

function chooseAnswer(questionIndex, optionIndex) {
  if (answers[questionIndex] !== undefined) {
    return;
  }

  answers[questionIndex] = optionIndex;
  render();
}

function renderResult() {
  let correct = 0;
  let answered = 0;

  questions.forEach((q, index) => {
    if (answers[index] !== undefined) {
      answered++;
    }

    if (answers[index] === q[2]) {
      correct++;
    }
  });

  document.getElementById("quizResult").innerHTML = `
    <div class="score">${correct}/${questions.length}</div>

    <p style="text-align:center">
      Правильных ответов: ${correct}
    </p>

    <p style="text-align:center">
      Отвечено: ${answered} из ${questions.length}
    </p>
  `;
}

function restartQuiz() {
  answers = {};
  current = quizStart;
  render();
}

