document.addEventListener("keydown", function(event) {
  if (event.key === "ArrowRight") {
    nextSlide();
  }

  if (event.key === "ArrowLeft") {
    previousSlide();
  }

  const slide = slides[currentSlide];

  if (
    slide.type === "quiz" &&
    quizAnswers[slide.questionIndex] === undefined
  ) {
    const keys = {
      "1": 0,
      "2": 1,
      "3": 2,
      "4": 3
    };

    const answerIndex = keys[event.key];

    if (answerIndex !== undefined) {
      chooseAnswer(slide.questionIndex, answerIndex);
    }
  }
});

