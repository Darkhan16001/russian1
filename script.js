function photo(caption) {
  return `
    <figure class="photo-card">
      <img
        src="${PHOTOS.portrait[0]}"
        alt="${caption}"
        data-photo="portrait"
        data-index="0"
      >
      <div class="photo-placeholder hidden">А. П.</div>
      <figcaption>${caption}</figcaption>
    </figure>
  `;
}

function setupPhotos() {
  screen.querySelectorAll("img[data-photo]").forEach(img => {
    const urls = PHOTOS[img.dataset.photo];

    function nextPhoto() {
      const next = Number(img.dataset.index) + 1;

      if (next < urls.length) {
        img.dataset.index = String(next);
        img.src = urls[next];
      } else {
        img.style.display = "none";
        img.parentElement
          .querySelector(".photo-placeholder")
          ?.classList.remove("hidden");
      }
    }

    img.addEventListener("error", nextPhoto);

    if (img.complete && img.naturalWidth === 0) {
      nextPhoto();
    }
  });
}

