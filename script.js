// 2. ЭЛЕМЕНТЫ ОФОРМЛЕНИЯ
// =====================================

function add(section, label, title, html, type = "normal") {
  slides.push({ section, label, title, html, type });
}

function card(title, body, color = "blue", icon = "✦") {
  return `
    <div class="card ${color}">
      <span class="card-icon">${icon}</span>
      <h3>${title}</h3>
      <p>${body}</p>
    </div>
  `;
}

function cards(items) {
  return `
    <div class="cards">
      ${items.map(item => card(...item)).join("")}
    </div>
  `;
}

function callout(text, color = "") {
  return `<div class="callout ${color}">${text}</div>`;
}

function list(items) {
  return `
    <ol class="tasks">
      ${items.map(item => `<li>${item}</li>`).join("")}
    </ol>
  `;
}

function notebook(title, content) {
  return `
    <div class="notebook">
      <h3>✍ ${title}</h3>
      ${content}
    </div>
  `;
}

function book(title, paragraphs) {
  return `
    <div class="book">
      <h3>${title}</h3>

      ${paragraphs.map(text => `<p>${text}</p>`).join("")}

      <small>
        А. П. Чехов · «Толстый и тонкий»
      </small>
    </div>
  `;
}

function answerButton(text) {
  return `
    <div style="margin-top:20px">
      <button class="action" onclick="showAnswer()">
        Показать ответ
      </button>
      <div id="answerBox" class="answer hidden">
        ${text}
      </div>
    </div>
  `;
}

// =====================================
// 3. ПРЕЗЕНТАЦИИ ВНУТРИ САЙТА
// =====================================

function presentationPage(
  section,
  title,
  imageFile,
  pdfFile,
  pageNumber,
  total
) {
  add(
    section,
    `ПРЕЗЕНТАЦИЯ · ${pageNumber} ИЗ ${total}`,
    title,
    `
      <figure class="presentation">
        <img
          src="assets/slides/${imageFile}"
          alt="${title} — слайд ${pageNumber}"
          loading="eager"
          onerror="
            this.style.display='none';
            this.nextElementSibling.classList.remove('hidden');
          "
        >

        <div class="fallback hidden">
          Изображение не найдено.
          Проверьте папку assets/slides.
        </div>

        <figcaption>
          Слайд ${pageNumber} из ${total}
        </figcaption>
      </figure>

      <a class="action"
         href="assets/${pdfFile}"
         target="_blank"
         rel="noopener noreferrer">
        Открыть полную презентацию
      </a>
    `,
    "presentation"
  );
}

