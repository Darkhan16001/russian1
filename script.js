function card(title, description, color = "blue", icon = "✦") {
  let cssClass = "";

  if (color === "red") {
    cssClass = "red-card";
  }

  if (color === "gold") {
    cssClass = "gold-card";
  }

  return `
    <div class="card ${cssClass}">
      <span class="card-icon">${icon}</span>
      <h3>${title}</h3>
      <p>${description}</p>
    </div>
  `;
}

function cards(items) {
  return `
    <div class="cards">
      ${items.map(item => card(...item)).join("")}
    </div>
  `;
}

function callout(text, color = "gold") {
  let cssClass = "";

  if (color === "blue") {
    cssClass = "blue-callout";
  }

  if (color === "red") {
    cssClass = "red-callout";
  }

  return `
    <div class="callout ${cssClass}">
      ${text}
    </div>
  `;
}

function list(items) {
  return `
    <ol class="tasks">
      ${items.map(item => `<li>${item}</li>`).join("")}
    </ol>
  `;
}

function notebook(title, content) {
  return `
    <div class="notebook">
      <h3>✍ ${title}</h3>
      ${content}
    </div>
  `;
}

function book(title, paragraphs) {
  return `
    <div class="book">
      <h3>${title}</h3>

      ${paragraphs.map(text => `<p>${text}</p>`).join("")}

      <p class="book-footer">
        А. П. Чехов · «Толстый и тонкий»
      </p>
    </div>
  `;
}

function photo(type, caption) {
  return `
    <figure class="photo-card">
      <img
        src="${PHOTOS[type][0]}"
        data-photo="${type}"
        data-index="0"
        alt="${caption}"
        loading="eager"
      >

      <div class="photo-fallback hidden">
        <b>А. П.</b>
        <span>Антон Павлович Чехов</span>
      </div>

      <figcaption>${caption}</figcaption>
    </figure>
  `;
}

