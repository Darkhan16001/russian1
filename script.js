function add(section, tag, title, html, type = "normal") {
  slides.push({ section, tag, title, html, type });
}

function card(title, body, color = "blue", icon = "✦") {
  return `
    <div class="card ${color}">
      <span class="card-icon">${icon}</span>
      <h3>${title}</h3>
      <p>${body}</p>
    </div>
  `;
}

function cards(items) {
  return `
    <div class="cards">
      ${items.map(item => card(...item)).join("")}
    </div>
  `;
}

function callout(text, color = "") {
  return `<div class="callout ${color}">${text}</div>`;
}

function list(items) {
  return `
    <ol class="tasks">
      ${items.map(item => `<li>${item}</li>`).join("")}
    </ol>
  `;
}

function notebook(title, text) {
  return `
    <div class="notebook">
      <h3>✍ ${title}</h3>
      ${text}
    </div>
  `;
}

function book(title, parts) {
  return `
    <div class="book">
      <h3>${title}</h3>
      ${parts.map(p => `<p>${p}</p>`).join("")}
      <small>А. П. Чехов · «Толстый и тонкий»</small>
    </div>
  `;
}

