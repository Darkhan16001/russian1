function renderQuiz(slide) {
  const index = slide.questionIndex;
  const question = questions[index];

  const selected = quizAnswers[index];
  const answered = selected !== undefined;

  let optionsHTML = "";

  question.options.forEach((option, optionIndex) => {
    let statusClass = "";

    if (answered) {
      if (optionIndex === question.correct) {
        statusClass = "correct";
      } else if (optionIndex === selected) {
        statusClass = "wrong";
      }
    }

    optionsHTML += `
      <button
        type="button"
        class="quiz-option ${statusClass}"
        onclick="chooseAnswer(${index}, ${optionIndex})"
        ${answered ? "disabled" : ""}
      >
        ${"ABCD"[optionIndex]}. ${option}
      </button>
    `;
  });

  let feedbackHTML = "";

  if (answered) {
    const correct = selected === question.correct;

    feedbackHTML = `
      <div class="quiz-feedback">
        <h3 class="${correct ? "green" : "red"}">
          ${correct ? "✓ Правильно!" : "✕ Неверно"}
        </h3>

        <p>
          <strong>Правильный ответ:</strong>
          ${question.options[question.correct]}
        </p>

        <p>${question.explanation}</p>
      </div>
    `;
  }

  screen.innerHTML = `
    <div class="eyebrow">
      ВОПРОС ${index + 1} ИЗ ${questions.length}
    </div>

    <h2>${question.question}</h2>

    <p>
      Выберите один правильный вариант.
    </p>

    <div class="quiz-options">
      ${optionsHTML}
    </div>

    ${feedbackHTML}
  `;
}

function chooseAnswer(questionIndex, optionIndex) {
  if (quizAnswers[questionIndex] !== undefined) {
    return;
  }

  quizAnswers[questionIndex] = optionIndex;
  renderSlide();
}

function renderQuizResult() {
  let correct = 0;
  let answered = 0;

  questions.forEach((question, index) => {
    if (quizAnswers[index] !== undefined) {
      answered++;
    }

    if (quizAnswers[index] === question.correct) {
      correct++;
    }
  });

  let message = "Повторите материал и попробуйте снова.";

  if (correct >= 13) {
    message = "Отлично! Вы хорошо усвоили материал.";
  } else if (correct >= 9) {
    message = "Хороший результат!";
  }

  document.getElementById("quizResult").innerHTML = `
    <div class="score">
      ${correct}/${questions.length}
    </div>

    <p style="text-align:center">
      ${message}
    </p>

    <p style="text-align:center">
      Отвечено: ${answered} из ${questions.length}
    </p>
  `;
}

function restartQuiz() {
  quizAnswers = {};
  currentSlide = quizStart;
  renderSlide();
}

