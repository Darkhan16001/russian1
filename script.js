function elapsedSeconds() {
  if (!timerRunning) {
    return elapsed;
  }

  return elapsed +
    Math.floor((Date.now() - timerStarted) / 1000);
}

function updateTimer() {
  const total = Math.max(0, elapsedSeconds());
  const minutes = Math.floor(total / 60);
  const seconds = total % 60;

  const element = document.getElementById("timer");

  element.textContent =
    String(minutes).padStart(2, "0") +
    ":" +
    String(seconds).padStart(2, "0");

  element.style.color =
    total >= 4800 ? "#cf3450" : "#11845b";
}

function toggleTimer() {
  if (timerRunning) {
    elapsed = elapsedSeconds();
    timerRunning = false;
  } else {
    timerStarted = Date.now();
    timerRunning = true;
  }

  document.getElementById("timerButton").textContent =
    timerRunning ? "⏸ Пауза" : "▶ Таймер";

  updateTimer();
}

function resetTimer() {
  elapsed = 0;
  timerStarted = 0;
  timerRunning = false;

  document.getElementById("timerButton").textContent =
    "▶ Таймер";

  updateTimer();
}

