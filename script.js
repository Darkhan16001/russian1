function add(section, label, title, html, type = "normal") {
  slides.push({
    section,
    label,
    title,
    html,
    type
  });
}

function card(title, description, color = "blue", icon = "✦") {
  return `
    <div class="card ${color}">
      <span class="card-icon">${icon}</span>
      <h3>${title}</h3>
      <p>${description}</p>
    </div>
  `;
}

function cards(items) {
  return `
    <div class="cards">
      ${items.map(item => card(...item)).join("")}
    </div>
  `;
}

function callout(text, color = "") {
  return `<div class="callout ${color}">${text}</div>`;
}

function list(items) {
  return `
    <ol class="tasks">
      ${items.map(item => `<li>${item}</li>`).join("")}
    </ol>
  `;
}

function notebook(title, content) {
  return `
    <div class="notebook">
      <h3>✍ ${title}</h3>
      ${content}
    </div>
  `;
}

function book(title, paragraphs) {
  return `
    <div class="book">
      <h3>${title}</h3>
      ${paragraphs.map(p => `<p>${p}</p>`).join("")}
      <small>А. П. Чехов · «Толстый и тонкий»</small>
    </div>
  `;
}

function reveal(text) {
  return `
    <button class="action" onclick="showAnswer()">
      Показать ответ
    </button>
    <div id="answerBox" class="answer hidden">
      ${text}
    </div>
  `;
}

